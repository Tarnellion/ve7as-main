/**
 * Общая сетевая идентичность конвейера.
 *
 * Строка одна на пробу и на сбор, и это не косметика. Пока их было две —
 * «feed availability probe» в пробе и «corpus harvest» в сборе, — проба меряла
 * доступность НЕ ТОГО клиента, который потом приходил за контентом, и её вывод
 * ничего не гарантировал. Так и потерялась группа isaguide: проба видела 200,
 * сбор молча получал 403.
 *
 * Причина 403 измерена 26.10.2026: на isa-guide.de стоит NinjaFirewall, и его
 * правило матчит подстроку «harvest» в User-Agent — без учёта регистра и без
 * границ слова («harvesting feeds» тоже 403). Слова crawler, spider, scraper,
 * indexer этот фаервол сегодня пропускает, но закладываться на чужой список
 * ключей незачем: он может пополниться.
 *
 * Отсюда форма строки. Никакого текстового хвоста с описанием цели — каждое
 * лишнее слово это ещё один шанс совпасть с чьим-то правилом. Product token по
 * RFC 9110, без притворства браузером: бот представляется ботом. Версия
 * снаружи, чтобы в чужих логах было видно, когда поведение конвейера
 * изменилось. Ссылка через «+» ведёт на страницу контактов (вебмастеру нужна
 * обратная связь, а не рассказ о проекте) и именно на локаль `en`: она
 * индексируемая и из публичного доступа не уйдёт.
 *
 * Провалидировано полным проходом по всем 17 лентам: везде 200.
 */
export const UA = 'Ve7asNewsBot/1.0 (+https://ve7as.com/en/contacts/)';

/**
 * Accept шлём явно, хотя чувствительности к нему не обнаружено (контрольные
 * пары на четырёх лентах с заголовком и без дали одинаковый ответ до байта).
 * Важно другое: он тоже обязан быть ОДИНАКОВЫМ в пробе и в сборе.
 */
export const ACCEPT = 'application/rss+xml, application/atom+xml, application/xml;q=0.9, text/html;q=0.8, */*;q=0.5';

/** Пауза между запросами к одному хосту. Crawl-delay не задан нигде, но долбить незачем. */
export const POLITE_MS = 2500;

export const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

export const headers = (extra = {}) => ({ 'User-Agent': UA, Accept: ACCEPT, ...extra });
