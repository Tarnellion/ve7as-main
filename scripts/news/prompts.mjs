/**
 * Промпты ступени 3. Единственное место, где формулируется, чего мы хотим
 * от модели.
 *
 * System собирается из docs/news/voice-guide.md, а не переписывается здесь:
 * гайд — утверждённый документ, и копия в коде немедленно разошлась бы с ним.
 * Правка гайда меняет все будущие тексты и обнуляет кэш промпта, поэтому он
 * правится редко и осознанно.
 *
 * Few-shot — абзацы из wagering-explained.en.md, материала, который редакция
 * признала хорошим (CV ритма 0.45 против 0.29-0.35 у служебных хабов).
 * Примеры даются ЦЕЛИКОМ абзацами, а не выжимкой: модель перенимает ритм,
 * а ритм на выжимке не виден.
 */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');

const VOICE_GUIDE = join(ROOT, 'docs', 'news', 'voice-guide.md');
const FEWSHOT_SOURCE = join(ROOT, 'docs', 'content-drafts', 'articles', 'wagering-explained.en.md');

/** Абзацы-образцы: берём средние по длине, пропуская врезки и служебное. */
function fewShot(limit = 4) {
  const raw = readFileSync(FEWSHOT_SOURCE, 'utf8')
    .replace(/^---[\s\S]*?---/m, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/```[\s\S]*?```/g, '');
  return raw
    .split(/\n\s*\n/)
    .map((p) => p.trim())
    .filter((p) => p && !/^[#>|\-*\d]/.test(p) && p.length > 180 && p.length < 900)
    .slice(0, limit);
}

/**
 * Часть гайда, которую читает модель: всё до маркера. Ниже маркера — разделы
 * для людей (раскрытие ИИ, схема конвейера), и их присутствие в промпте не
 * безвредно: на первом боевом прогоне модель исполнила раздел о раскрытии
 * буквально и дописала в статью ложную строку о проверке редактором, а из
 * описания постпроцессора вывела, что «две группы нужны всегда».
 *
 * Нет маркера — падаем, а не отдаём весь файл молча.
 */
const GUIDE_END = '<!-- ДАЛЬШЕ ТОЛЬКО ДЛЯ ЛЮДЕЙ';
function guideForModel() {
  const raw = readFileSync(VOICE_GUIDE, 'utf8');
  const end = raw.indexOf(GUIDE_END);
  if (end === -1) {
    throw new Error(`В ${VOICE_GUIDE} нет маркера «${GUIDE_END}»: без него в промпт уйдёт весь файл, ` +
      'включая служебные разделы для людей.');
  }
  return raw.slice(0, end).trimEnd();
}

