/**
 * Промпты ступени 3. Единственное место, где формулируется, чего мы хотим
 * от модели.
 *
 * System собирается из docs/news/voice-guide.md, а не переписывается здесь:
 * гайд — утверждённый документ, и копия в коде немедленно разошлась бы с ним.
 * Правка гайда меняет все будущие тексты и обнуляет кэш промпта, поэтому он
 * правится редко и осознанно.
 *
 * Few-shot — абзацы из wagering-explained.en.md, материала, который редакция
 * признала хорошим (CV ритма 0.45 против 0.29-0.35 у служебных хабов).
 * Примеры даются ЦЕЛИКОМ абзацами, а не выжимкой: модель перенимает ритм,
 * а ритм на выжимке не виден.
 */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');

const VOICE_GUIDE = join(ROOT, 'docs', 'news', 'voice-guide.md');
const FEWSHOT_SOURCE = join(ROOT, 'docs', 'content-drafts', 'articles', 'wagering-explained.en.md');

/** Абзацы-образцы: берём средние по длине, пропуская врезки и служебное. */
function fewShot(limit = 4) {
  const raw = readFileSync(FEWSHOT_SOURCE, 'utf8')
    .replace(/^---[\s\S]*?---/m, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/```[\s\S]*?```/g, '');
  return raw
    .split(/\n\s*\n/)
    .map((p) => p.trim())
    .filter((p) => p && !/^[#>|\-*\d]/.test(p) && p.length > 180 && p.length < 900)
    .slice(0, limit);
}

/**
 * Общий system для всех текстовых шагов. Кэшируется целиком: при синхронном
 * прогоне это $0.20 за миллион вместо $4.00. В батче попадание в кэш не
 * гарантировано (TTL 5 минут против суточного окна), и это учтено в бюджете.
 */
export function systemPrompt() {
  return [
    {
      type: 'text',
      text:
        'Ты пишешь для Ve7as — портала о математике азартных игр (вероятности, RTP, кромка казино, вейджер). ' +
        'Ниже редакционный гайд голоса. Это не пожелания, а требования: текст, нарушающий их, вернётся на правку.\n\n' +
        readFileSync(VOICE_GUIDE, 'utf8'),
      cache_control: { type: 'ephemeral' },
    },
    {
      type: 'text',
      text:
        'Образцы ритма — абзацы из материала, который редакция признала хорошим. ' +
        'Перенимай длину и неровность, а не тему:\n\n' +
        fewShot().map((p, i) => `[${i + 1}] ${p}`).join('\n\n'),
      cache_control: { type: 'ephemeral' },
    },
  ];
}

/** Схема фактов. Структурированный вывод, чтобы не парсить прозу регуляркой. */
export const FACTS_SCHEMA = {
  type: 'json_schema',
  schema: {
    type: 'object',
    additionalProperties: false,
    required: ['event', 'facts', 'unconfirmed'],
    properties: {
      event: { type: 'string', description: 'Что произошло, одним предложением, с датой' },
      facts: {
        type: 'array',
        items: {
          type: 'object',
          additionalProperties: false,
          required: ['statement', 'attribution', 'sourceGroups'],
          properties: {
            statement: { type: 'string', description: 'Утверждение. Число, дата или имя, а не обобщение' },
            attribution: { type: 'string', description: 'Кто это сообщает: регулятор, оператор, издание' },
            sourceGroups: {
              type: 'array', items: { type: 'string' },
              description: 'Группы независимости, подтверждающие факт',
            },
          },
        },
      },
      unconfirmed: {
        type: 'array', items: { type: 'string' },
        description: 'Утверждения из одного источника — в текст идут только с явной оговоркой',
      },
    },
  },
};

/**
 * Шаг 1 — извлечение фактов. Модель видит исходные статьи ТОЛЬКО здесь.
 * Дальше по конвейеру идут факты, и перефразировать уже нечего: это и есть
 * конструктивный запрет на рерайт, а не просьба «не копируй».
 */
export function extractFactsPrompt(event, documents) {
  return [
    {
      role: 'user',
      content:
        `Событие: ${event.title}\n` +
        `Подтверждают независимые группы: ${event.confirmingGroups.join(', ')} (${event.voices} голоса).\n\n` +
        `Извлеки факты из публикаций ниже. Правила:\n` +
        `— Факт идёт в основной список, только если его сообщают минимум две независимые группы. Всё остальное — в unconfirmed.\n` +
        `— Утверждение должно нести число, дату, имя или сумму. Обобщения вроде «регулятор ужесточил требования» не факт.\n` +
        `— Пресс-релиз оператора никогда не бывает единственным подтверждением.\n` +
        `— Ничего не додумывай: если в текстах нет суммы штрафа, её нет и у тебя.\n\n` +
        documents
          .map((d) => `=== ${d.group} (${d.sourceType}) · ${d.url}\n${d.text}`)
          .join('\n\n'),
    },
  ];
}

/** Шаг 2 — черновик. Исходников здесь уже нет, только факты. */
export function draftPrompt(event, facts, lang = 'en') {
  return [
    {
      role: 'user',
      content:
        `Напиши новостной материал на ${lang === 'es' ? 'испанском' : 'английском'} по фактам ниже.\n\n` +
        `Объём 450–650 слов. Markdown, без заголовка H1 — он задаётся отдельно.\n` +
        `Начни с того, что произошло: дата, сумма, имя. Не с подводки.\n` +
        `Каждое утверждение, взятое из unconfirmed, помечай явно («оператор заявляет», «по данным одного издания»).\n` +
        `Если тема допускает собственный расчёт по нашим данным (вероятность, кромка, матожидание) — ровно один абзац с ним. ` +
        `Нет данных — абзаца нет; выдумывать число нельзя.\n` +
        `Соблюдай профиль ритма из гайда: абзацы разной длины, не меньше пятой части — однопредложенные.\n\n` +
        `ФАКТЫ:\n${JSON.stringify(facts, null, 1)}`,
    },
  ];
}

/** Шаг 3 — критика. Отдельный проход, потому что правка себя же слепа к своим штампам. */
export function critiquePrompt(draft, facts) {
  return [
    {
      role: 'user',
      content:
        `Ниже черновик и факты, из которых он написан. Ты редактор, который ищет, за что вернуть материал.\n\n` +
        `Проверь по пунктам и для каждого дай либо «ок», либо конкретное замечание с цитатой:\n` +
        `1. Есть ли утверждение, которого нет в фактах (выдумано или достроено)?\n` +
        `2. Есть ли утверждение из unconfirmed без оговорки об источнике?\n` +
        `3. Есть ли обобщение там, где в фактах было число?\n` +
        `4. Штампы из запрет-листа гайда.\n` +
        `5. Ритм: ровные абзацы, тройки, абзац-резюме в конце.\n` +
        `6. Противоречит ли текст рамке: мы объясняем математику, не зовём играть и не отговариваем.\n\n` +
        `Верни список замечаний. Если возвращать не за что — одна строка «БЕЗ ЗАМЕЧАНИЙ».\n\n` +
        `ЧЕРНОВИК:\n${draft}\n\nФАКТЫ:\n${JSON.stringify(facts, null, 1)}`,
    },
  ];
}

/** Шаг 4 — правка по замечаниям. */
export function revisePrompt(draft, critique, rhythmHint) {
  return [
    {
      role: 'user',
      content:
        `Исправь черновик по замечаниям редактора. Меняй только то, на что указано: ` +
        `переписывание целиком теряет то, что уже хорошо.\n\n` +
        (rhythmHint ? `Отдельно по ритму (замер кодом, не мнение): ${rhythmHint}\n\n` : '') +
        `ЗАМЕЧАНИЯ:\n${critique}\n\nЧЕРНОВИК:\n${draft}\n\n` +
        `Верни только исправленный текст, без пояснений.`,
    },
  ];
}

