/**
 * Фильтр значимости: отличает новость от корпоративного анонса.
 *
 * Зачем отдельно от дедупликации. Правило двух независимых групп проверяет,
 * ПОДТВЕРЖДЕНО ли событие, и ничего не говорит о том, стоит ли оно публикации.
 * Вендорский анонс, перепечатанный двумя изданиями разными словами, правило
 * проходит честно: групп действительно две, синдикацией по точному заголовку
 * это не ловится. На корпусе 26.10.2026 так в очередь модерации попали награда
 * EGT, контент-сделка Zitro и павильон на выставке ICE.
 *
 * КТО ЧИТАТЕЛЬ — отсюда всё остальное. Ve7as это потребительский
 * портал-объяснитель про вероятность: RTP, коэффициенты, вейджер, базовая
 * стратегия. Читатель — игрок. Поэтому отраслевая пресса и мы считаем новостью
 * разное: сделка поставщика об интеграции контента для B2B-издания главный
 * материал дня, для нашего читателя — пустое место. Фильтр отражает нашего
 * читателя, а не редакцию источника.
 *
 * НАПРАВЛЕНИЕ ОШИБКИ выбрано сознательно. Пропущенный анонс стоит владельцу
 * одного взгляда в очереди; выброшенная новость теряется молча. Поэтому правило
 * настроено на уверенное отбрасывание, а не на полноту, и отсеянное не
 * удаляется, а показывается отдельным разделом отчёта.
 *
 * КАК ПОЛУЧЕНО. Корпус из 196 событий размечен тремя независимыми разметчиками
 * на каждое событие (новость / промо / пограничное), решает большинство.
 * Единогласных решений 94%, случаев без большинства нет. Распределение:
 * 83 новости, 79 промо, 38 пограничных.
 *
 * Что из признаков РАЗДЕЛЯЕТ (доля не-новостей среди событий с признаком):
 *
 *   промо-маркер в заголовке         28 из 32   88%   отбрасывает
 *   заголовок капсом                  4 из 4   100%   отбрасывает
 *   заголовок короче 5 слов           4 из 4   100%   отбрасывает
 *   регуляторное действие в заголовке 4 из 29   14%   ЗАЩИЩАЕТ (86% новостей)
 *
 * Что НЕ разделяет и потому не используется: наличие денежной суммы (44%
 * не-новостей против базовых 58%), участие регулятора в кластере (43%),
 * наличие пресс-релизной группы (40%). Каждый из них выглядел осмысленным
 * и не подтвердился.
 *
 * ПОЧЕМУ ПРАВИЛО ИМЕННО ТАКОЕ. Проверены четыре варианта. Расширение на
 * промо-маркер в ЛИДЕ (а не только в заголовке) поднимает полноту по корпусу
 * с 25% до 37%, но в очереди модерации не ловит НИ ОДНОГО промо сверх тех же
 * пяти — и при этом выбрасывает настоящую новость (кампания регулятора Дании
 * о гэмблинг-механиках в детских играх). То же у двух остальных вариантов.
 * Поэтому взят самый узкий: он строго лучше на той выборке, ради которой
 * фильтр и существует.
 *
 * РЕЗУЛЬТАТ на корпусе: из 196 событий отсеяно 29, настоящих новостей среди
 * них НОЛЬ. В очереди модерации отсеяно 5 из 9 промо и пограничных, новостей
 * потеряно ноль; очередь сократилась с 27 до 22, доля шума в ней — с 33% до 18%.
 *
 * ИЗВЕСТНЫЙ ПРЕДЕЛ. В очереди остаются два промо без ключевых слов
 * («NOVOMATIC concludes GAT Bogotá», «CEO reveals ambitious Finland plans») и
 * два пограничных — выступление Стива Уинна и ограбление у казино. Последние
 * это ДРУГОЙ класс: светская хроника и местная уголовщина, и ловить их
 * промо-маркерами нельзя — слова о преступлении совпадут с защитным признаком
 * правоприменения. Их разведёт ступень извлечения фактов.
 */

/**
 * Границы слова обязательны у КАЖДОГО маркера. Без них регулярка ловит
 * подстроки, и это не теория: `wins?` срабатывал внутри бренда «bwin», а
 * испанское `presenta` — внутри «representación». Обе ошибки выбрасывали
 * настоящие новости и найдены только замером по разметке.
 */
const word = (list) => new RegExp(list.map((m) => `\\b${m}`).join('|'), 'i');

/** Регуляторное и судебное действие. Защитный признак: 86% таких — новости. */
const ENFORCEMENT = word([
  'fine[sd]?\\b', 'fining\\b', 'penalt', 'sanction', 'sentenc', 'convict', 'prosecut',
  'court\\b', 'lawsuit', 'sues?\\b', 'sued\\b', 'injunction', 'appeal',
  'ban(?:s|ned|ning)?\\b', 'revok', 'suspend', 'investigat', 'raid', 'seiz',
  'fraud', 'launder', 'match-?fixing', 'illegal', 'unlicensed', 'breach', 'failures?\\b',
  'multa', 'sanci[oó]n', 'condena', 'tribunal', 'demanda', 'prohib', 'ilegal',
  'boete', 'verbod', 'illegaal', 'onderzoek',
  'Bu[ßs]geld', 'Strafe', 'Gericht', 'Verbot', 'Versto[ßs]',
]);

/** Корпоративный анонс: убери название компании — не останется ничего. */
const PROMO = word([
  'award', 'shortlist', 'nominat', 'wins?\\b', 'winner', 'honou?red', 'recogni[sz]ed',
  'exhibit', 'booth', 'showcase', 'pavilion',
  'partnership', 'partners with', 'teams? up', 'signs? (?:deal|agreement|content)',
  'integrat', 'goes live with', 'launch', 'unveil', 'debuts?\\b', 'rolls? out',
  'appoint', 'joins as', 'names? new', 'hires?\\b', 'promoted to',
  'pleased to announce', 'proud to',
  'premio', 'galard', 'reconocid', 'incorpora', 'lanza', 'alianza', 'nombra',
  'pr[eê]mio', 'premiado', 'lan[çc]a', 'parceria',
  'Auszeichnung', 'ausgezeichnet', 'Partnerschaft',
]);

/** Доля прописных среди букв. Заголовок целиком капсом — перепечатанный релиз. */
function capsRatio(title) {
  const letters = [...title].filter((c) => /\p{L}/u.test(c));
  if (!letters.length) return 0;
  return letters.filter((c) => c === c.toUpperCase() && c !== c.toLowerCase()).length / letters.length;
}

/**
 * Оценка значимости. Решение принимается по ЗАГОЛОВКУ: расширение на лид
 * измерено и отвергнуто — полноты в очереди не добавляет, новости теряет.
 */
export function assess(title = '', lead = '') {
  const signals = {
    promoTitle: PROMO.test(title),
    enforcementTitle: ENFORCEMENT.test(title),
    caps: capsRatio(title) > 0.8,
    shortTitle: title.split(/\s+/).filter(Boolean).length <= 4,
    // Считается, но в решении НЕ участвует: на разметке не разделяет.
    // Остаётся в выдаче, чтобы следующая калибровка шла по тем же числам.
    promoLead: PROMO.test(lead),
    enforcementLead: ENFORCEMENT.test(lead),
  };

  if (signals.caps) return { newsworthy: false, reason: 'заголовок капсом', signals };
  if (signals.shortTitle) return { newsworthy: false, reason: 'заголовок короче пяти слов', signals };
  if (signals.promoTitle && !signals.enforcementTitle) {
    return { newsworthy: false, reason: 'корпоративный анонс в заголовке', signals };
  }
  return { newsworthy: true, reason: '', signals };
}
